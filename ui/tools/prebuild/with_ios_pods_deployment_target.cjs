const { withPodfile } = require("expo/config-plugins");

const POST_INSTALL_CALL = `    react_native_post_install(
      installer,
      config[:reactNativePath],
      :mac_catalyst_enabled => false,
      :ccache_enabled => ccache_enabled?(podfile_properties),
    )`;

const MANAGED_BLOCK_START = "    # @generated by with-ios-pods-deployment-target";
const MANAGED_BLOCK_END = "    # @end generated by with-ios-pods-deployment-target";

function createManagedBlock(deploymentTarget) {
  return `${MANAGED_BLOCK_START}
    minimum_ios_deployment_target = Gem::Version.new('${deploymentTarget}')
    installer.pods_project.targets.each do |pod_target|
      pod_target.build_configurations.each do |build_configuration|
        configured_target = build_configuration.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        next if configured_target.nil?

        if Gem::Version.new(configured_target) < minimum_ios_deployment_target
          build_configuration.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = minimum_ios_deployment_target.to_s
        end
      end
    end
${MANAGED_BLOCK_END}`;
}

function updatePodfile(contents, deploymentTarget) {
  const managedBlockPattern = new RegExp(
    `${MANAGED_BLOCK_START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${MANAGED_BLOCK_END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`,
  );
  const managedBlock = createManagedBlock(deploymentTarget);

  if (managedBlockPattern.test(contents)) {
    return contents.replace(managedBlockPattern, managedBlock);
  }

  if (!contents.includes(POST_INSTALL_CALL)) {
    throw new Error("无法在 Podfile 中定位 react_native_post_install，无法设置 Pods deployment target。");
  }

  return contents.replace(POST_INSTALL_CALL, `${POST_INSTALL_CALL}\n\n${managedBlock}`);
}

module.exports = function withIosPodsDeploymentTarget(config, options = {}) {
  const deploymentTarget = options.deploymentTarget;
  if (typeof deploymentTarget !== "string" || !/^\d+(?:\.\d+)?$/.test(deploymentTarget)) {
    throw new Error("with-ios-pods-deployment-target 需要合法的 deploymentTarget，例如 15.1。");
  }

  return withPodfile(config, (modConfig) => {
    modConfig.modResults.contents = updatePodfile(
      modConfig.modResults.contents,
      deploymentTarget,
    );
    return modConfig;
  });
};

