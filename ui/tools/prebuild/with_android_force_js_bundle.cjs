const { withAppBuildGradle } = require("@expo/config-plugins");

const MARKER = "// @generated by with_android_force_js_bundle";

const GRADLE_CONFIG = `
${MARKER}
// Metro 的输入可能位于 Android 工程之外，例如 monorepo 或 node_modules。
// Gradle 无法可靠感知所有变更，因此每次构建都重新生成嵌入式 JS Bundle，
// 同时保留 Java、Kotlin 和 C++ 等原生编译缓存。
tasks.configureEach { task ->
    if (
        task.name.startsWith("createBundle") &&
        task.name.endsWith("JsAndAssets")
    ) {
        task.outputs.upToDateWhen { false }
    }
}
`;

module.exports = function withAndroidForceJsBundle(config) {
  return withAppBuildGradle(config, (modConfig) => {
    if (modConfig.modResults.language !== "groovy") {
      throw new Error("with_android_force_js_bundle 仅支持 Groovy build.gradle");
    }

    if (!modConfig.modResults.contents.includes(MARKER)) {
      modConfig.modResults.contents = `${modConfig.modResults.contents.trimEnd()}\n${GRADLE_CONFIG}`;
    }

    return modConfig;
  });
};
